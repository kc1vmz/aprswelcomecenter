/* TinyTopics configuration and durable content diagnostics for the policy editor. */
window.policyContent = (() => {
    const form = document.querySelector('#policy-form');
    const selector = document.querySelector('#policy-topic');
    const parameters = document.querySelector('#policy-topic-parameters');
    const notice = document.querySelector('#policy-topic-message');
    const history = document.querySelector('#policy-content-history');
    const buttons = Array.from(document.querySelectorAll('[data-policy-content]'));
    let source = 'TEXT';
    let topicId = '';
    let topics = [];
    let drafts = new Map();
    let generation = 0;
    let available = false;

    function generated() {
        return communicationCategories.get(form.elements.categoryId.value)?.autoGeneratedText === true;
    }

    function update() {
        const automatic = generated();
        const tiny = !automatic && source === 'TINYTOPICS';
        buttons.forEach(button => {
            button.disabled = automatic;
            button.setAttribute('aria-pressed', String(button.dataset.policyContent === (automatic ? 'TEXT' : source)));
        });
        document.querySelector('#policy-text-field').hidden = tiny;
        document.querySelector('#policy-topic-fields').hidden = !tiny;
        form.elements.messageText.disabled = automatic || tiny;
        form.elements.messageText.required = !automatic && !tiny
            && ['SCHEDULED_ONCE', 'SCHEDULED_RECURRING', 'SHRIEK_HEARD'].includes(form.elements.communicationEventType.value);
        selector.disabled = !tiny || !available;
        parameters.querySelectorAll('input').forEach(input => { input.disabled = !tiny; });
    }

    function renderParameters() {
        parameters.replaceChildren();
        const draft = drafts.get(topicId) || {};
        const definition = topics.find(topic => topic.id === topicId);
        const names = new Set([...(definition?.parameterNames || []), ...Object.keys(draft)]);
        for (const name of names) {
            if (name === 'length' || name === 'format') continue;
            if (!Object.hasOwn(draft, name)) draft[name] = '';
            drafts.set(topicId, draft);
            const label = document.createElement('label');
            label.textContent = name;
            const input = document.createElement('input');
            input.type = 'text';
            input.maxLength = 4000;
            input.value = draft[name] ?? '';
            input.placeholder = 'Optional; blank uses the topic default';
            input.addEventListener('input', () => {
                const next = {...(drafts.get(topicId) || {})};
                next[name] = input.value;
                drafts.set(topicId, next);
            });
            label.append(input);
            parameters.append(label);
        }
        update();
    }

    function option(value, text) {
        const node = document.createElement('option');
        node.value = value;
        node.textContent = text;
        selector.append(node);
    }

    async function loadHistory(policy, current) {
        history.replaceChildren();
        if (!policy?.id) return;
        try {
            const response = await fetch(`/api/v1/communication-policies/${policy.id}/content-results`);
            if (!response.ok) throw new Error();
            const rows = await response.json();
            if (current !== generation || !rows.length) return;
            const details = document.createElement('details');
            const summary = document.createElement('summary');
            summary.textContent = `TinyTopics content history — latest: ${rows[0].CONTENT_STATUS}`;
            details.append(summary);
            for (const row of rows) {
                const entry = document.createElement('p');
                entry.textContent = `${new Date(row.REQUESTED_AT).toLocaleString()} — ${row.TOPIC_ID}: ${row.CONTENT_STATUS}`
                    + (row.HTTP_STATUS ? ` (HTTP ${row.HTTP_STATUS})` : '')
                    + (row.ERROR_MESSAGE ? `. ${row.ERROR_MESSAGE}` : '')
                    + `. Text: ${row.RESOLVED_TEXT}`;
                details.append(entry);
            }
            history.append(details);
        } catch {
            if (current === generation) history.textContent = 'TinyTopics content history could not be loaded.';
        }
    }

    async function load(policy) {
        const current = ++generation;
        source = policy?.contentSource || 'TEXT';
        topicId = policy?.topicId || '';
        topics = [];
        available = false;
        drafts = new Map(topicId ? [[topicId, {...policy.topicParameters}]] : []);
        selector.replaceChildren();
        option('', 'Loading topics…');
        notice.textContent = topicId ? `Saved topic: ${topicId}` : '';
        renderParameters();
        void loadHistory(policy, current);
        try {
            const response = await fetch('/api/v1/tiny-topics/topics', {cache: 'no-store'});
            if (!response.ok) throw new Error();
            const rows = await response.json();
            if (current !== generation) return;
            topics = rows;
            available = topics.length > 0;
            selector.replaceChildren();
            option('', available ? 'Choose a topic' : 'No topics available');
            topics.forEach(topic => option(topic.id, topic.description ? `${topic.id} — ${topic.description}` : topic.id));
            if (topicId && !topics.some(topic => topic.id === topicId)) {
                if (available) option(topicId, `${topicId} (saved topic unavailable)`);
                notice.textContent = `Saved topic ${topicId} is unavailable. Its saved parameters are preserved.`;
            } else {
                const declared = topics.find(topic => topic.id === topicId)?.parameterNames || [];
                const obsolete = Object.keys(drafts.get(topicId) || {}).filter(name => !declared.includes(name));
                notice.textContent = obsolete.length ? `Parameters no longer declared by this topic: ${obsolete.join(', ')}. Clear their values to omit them from requests.` : '';
            }
            selector.value = available ? topicId : '';
            renderParameters();
        } catch {
            if (current !== generation) return;
            available = false;
            selector.replaceChildren();
            option('', 'No topics available');
            notice.textContent = 'TinyTopics could not be reached or returned an invalid topic list.'
                + (topicId ? ` Saved topic ${topicId} and its parameters are preserved.` : '');
            update();
        }
    }

    selector.addEventListener('change', () => {
        topicId = selector.value;
        notice.textContent = '';
        renderParameters();
    });
    buttons.forEach(button => button.addEventListener('click', () => {
        source = button.dataset.policyContent;
        update();
    }));
    return {load, update, value: () => generated()
        ? {contentSource: 'TEXT', topicId: null, topicParameters: {}}
        : {contentSource: source, topicId: topicId || null, topicParameters: {...(drafts.get(topicId) || {})}}};
})();
