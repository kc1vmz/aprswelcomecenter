package com.kc1vmz.aprswc.controller;

import com.kc1vmz.aprswc.communication.MessageDeliveryService;
import java.util.List;
import java.util.Map;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
public class MessageDeliveryController {
    private final MessageDeliveryService deliveries;

    public MessageDeliveryController(MessageDeliveryService deliveries) {
        this.deliveries = deliveries;
    }

    @GetMapping("/api/v1/message-deliveries")
    public List<Map<String, Object>> history() {
        return deliveries.history();
    }
}
